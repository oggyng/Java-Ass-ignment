    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        eCPass.setText("*This Field cannot be empty!");
        eName.setVisible(false);
        eMail.setVisible(false);
        ePass.setVisible(false);
        eCPass.setVisible(false);
        eDay.setVisible(false);
        
        if(NameField.getText().length()==0){eName.setVisible(true);return;}
        if(MailField.getText().length()==0){eMail.setVisible(true);return;}
        if(PassField.getPassword().length==0){ePass.setVisible(true);return;}
        if(CPassField.getPassword().length==0){eCPass.setVisible(true);return;}
        if(role.equals("Counselor")){
            if(!mon.isSelected()&&!tue.isSelected()&&!wed.isSelected()&&!thu.isSelected()&&!fri.isSelected()){
                eDay.setVisible(true);
                return;
            }
        }
        
        String pass = new String(PassField.getPassword());
        String cpass = new String(CPassField.getPassword());
        if(!pass.equals(cpass)){
            eCPass.setText("*Password does not match!");
            eCPass.setVisible(true);
            return;
        }
        
        if(JOptionPane.showConfirmDialog(frame, "Are you sure you want to update?")==0){
            String name = NameField.getText().trim();
            String mail = MailField.getText().trim();
            
            String loginTxt = user.getId()+","+name+","+pass+","+role;
            user.setName(name);
            user.setEmail(mail);
            Functions.removeData(user.getId(), "loginData.txt");
            Functions.removeData(user.getId(), "userData.txt");
            user.initData();
            Functions.inputFile("loginData.txt", loginTxt, "append");
            if(role.equals("Counselor")){
                String cProTxt = user.getId()+","+ Boolean.toString(mon.isSelected())+","+Boolean.toString(tue.isSelected())+","+Boolean.toString(wed.isSelected())+","+Boolean.toString(thu.isSelected())+","+Boolean.toString(fri.isSelected())+","+specBox.getSelectedItem();
                Functions.removeData(user.getId(), "cProfile.txt");
                Functions.inputFile("cProfile.txt",cProTxt,"append");
            }
            JOptionPane.showMessageDialog(frame,"Profile updated successfully!");
            
        }
        

        
    }//GEN-LAST:event_jButton1ActionPerformed

